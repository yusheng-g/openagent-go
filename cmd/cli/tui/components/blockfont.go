// Package blockfont renders text as a 7-wide × 9-tall pixel font using
// half-block glyphs (█ ▀ ▄) for smooth curves and diagonals. Each rendered
// row is composed from two sub-rows (upper + lower), so the bitmap is 7×18.
//
// Only A-Z, a-z, 0-9 are supported. Every other rune is filtered to a
// space. Case is preserved (upper and lower have distinct glyphs).
//
// Layout (four-line three-grid, mapped to 9 rows):
//   rows 0-2: upper zone (ascenders for b d f h k l t)
//   rows 3-5: middle zone (x-height bodies)
//   rows 6-8: lower zone (descenders for g j p q y)
// Uppercase + digits occupy rows 0-5 (upper + middle).

const (
	glyphWidth  = 7
	glyphHeight = 9  // rendered rows (█/▀▄)
	subHeight   = 18 // bitmap sub-rows (2 per rendered row)

	// compactGlyphWidth/Height render the same glyphs at a smaller 5×7 size
	// (used for the welcome logo); the smaller bitmaps are derived from the
	// 7×9 glyphs by box-merging, so the pixel style is preserved.
	compactGlyphWidth  = 5
	compactGlyphHeight = 7
)

